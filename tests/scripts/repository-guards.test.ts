import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";

import { describe, expect, test } from "vitest";
import { fileNameProblems, inlineStyleProblems } from "../../scripts/check-conventions.mjs";
import { emDashApplies, findTextProblems } from "../../scripts/check-text.mjs";
import {
  ALLOWED_COMMIT_EMAILS,
  commitMessageProblems,
  isAllowedIdentity,
} from "../../scripts/git-hooks.mjs";

// Built from code points so this file passes the check it tests.
const EM_DASH = String.fromCodePoint(0x2014);
const EN_DASH = String.fromCodePoint(0x2013);
const ROCKET = String.fromCodePoint(0x1f680);
const CHECK_MARK = String.fromCodePoint(0x2705);
const COPYRIGHT = String.fromCodePoint(0xa9);
const ARROW = String.fromCodePoint(0x2194);

describe("findTextProblems", () => {
  test("flags an em dash only where the rule applies", () => {
    const text = `a ${EM_DASH} b`;
    expect(findTextProblems(text, { label: "f", emDash: true })).toEqual([
      expect.stringContaining("f:1: em dash"),
    ]);
    expect(findTextProblems(text, { label: "f", emDash: false })).toEqual([]);
  });

  test("accepts an en dash", () => {
    expect(findTextProblems(`a ${EN_DASH} b`, { label: "f", emDash: true })).toEqual([]);
  });

  test("flags emoji everywhere, but not text symbols or plain arrows", () => {
    expect(findTextProblems(ROCKET, { label: "f", emDash: false })).toEqual(["f:1: emoji"]);
    expect(findTextProblems(CHECK_MARK, { label: "f", emDash: false })).toEqual(["f:1: emoji"]);
    expect(findTextProblems(`${COPYRIGHT} ${ARROW}`, { label: "f", emDash: false })).toEqual([]);
  });
});

describe("emDashApplies", () => {
  test("covers the code layer", () => {
    expect(emDashApplies("src/ui/app.tsx")).toBe(true);
    expect(emDashApplies("tests/golden/headless.ts")).toBe(true);
  });

  test("leaves docs, scripts and root files to the house style", () => {
    expect(emDashApplies("docs/decisions/autosave.md")).toBe(false);
    expect(emDashApplies("scripts/balance.ts")).toBe(false);
    expect(emDashApplies("README.md")).toBe(false);
    expect(emDashApplies("docs/src/notes.md")).toBe(false);
  });
});

describe("commitMessageProblems", () => {
  test("accepts a plain conventional message", () => {
    expect(commitMessageProblems("fix(ui): keep the badge colour in a token\n\nBody.")).toEqual([]);
  });

  test.each([
    "Co-authored-by: Someone <someone@example.com>",
    "Co-Authored-By: Anna <a@example.com>",
    "Generated with some tool",
    "Generated by some tool",
  ])("rejects a co-author or generated-by line: %s", (trailer) => {
    expect(commitMessageProblems(`feat: add x\n\n${trailer}`)).toEqual([
      expect.stringContaining("attribution"),
    ]);
  });

  test("keeps prose that merely mentions generated values", () => {
    expect(commitMessageProblems("feat: add x\n\nValues generated by the script.")).toEqual([]);
  });

  test("rejects emoji and em dash, ignoring comment lines", () => {
    expect(commitMessageProblems(`feat: add x ${ROCKET}`)).toEqual(["commit message:1: emoji"]);
    expect(commitMessageProblems(`feat: add x\n\na ${EM_DASH} b`)).toHaveLength(1);
    expect(commitMessageProblems(`feat: add x\n# ${EM_DASH} ${ROCKET}`)).toEqual([]);
  });
});

describe("isAllowedIdentity", () => {
  test("accepts only the owner's e-mail, case-insensitively, ignoring the timestamp", () => {
    const [owner = ""] = ALLOWED_COMMIT_EMAILS;
    expect(isAllowedIdentity(`visvaya <${owner}> 1790000000 +0200`)).toBe(true);
    expect(isAllowedIdentity(`Anyone <${owner.toUpperCase()}> 1790000000 +0200`)).toBe(true);
    expect(isAllowedIdentity("Someone <someone@example.com> 1790000000 +0200")).toBe(false);
    expect(isAllowedIdentity("visvaya 1790000000 +0200")).toBe(false);
  });
});

describe("check-conventions", () => {
  test("file names: kebab-case in code trees, docs left alone", () => {
    expect(fileNameProblems("src/ui/player-card.tsx")).toEqual([]);
    expect(fileNameProblems("tests/golden/a-01.replay.json")).toEqual([]);
    expect(fileNameProblems("src/ui/PlayerCard.tsx")).toHaveLength(1);
    expect(fileNameProblems("public/licenses/figtree-OFL.txt")).toEqual([]);
    expect(fileNameProblems("docs/decisions/_rho-2026-09-01.md")).toEqual([]);
  });

  test("inline styles only for custom properties", () => {
    expect(inlineStyleProblems("src/ui/a.tsx", 'style={{ "--dd-x": v } as CSSProperties}')).toEqual(
      []
    );
    expect(inlineStyleProblems("src/ui/a.tsx", "style={{ background: v }}")).toHaveLength(1);
  });
});

describe("temp directories only through tests/temp-dir.ts", () => {
  // This file's own path, excluded from the scan below so its allowlist
  // strings and this comment cannot trip the guard it defines.
  const GUARD_FILE = "tests/scripts/repository-guards.test.ts";
  const HELPER_FILE = "tests/temp-dir.ts";

  // Files allowed to create their own temp directory outside the helper,
  // each with a one-line reason. Every entry here must still clean up after
  // itself; the guard only checks who is allowed to call mkdtemp at all.
  const ALLOWLIST: Record<string, string> = {
    "tests/scripts/value-curve-fit.test.ts":
      "suite-scoped dir rooted at testTempRoot(), cleaned up in finally",
    "tests/scripts/opening-budget-activation-report.test.ts":
      "suite-scoped dir rooted at testTempRoot(), cleaned up in afterAll",
  };

  // Built from parts so this file does not fail its own check: the literal
  // word would otherwise appear in this file too (in this comment, in the
  // allowlist reasons above, and in the assertions below).
  const NEEDLE = ["mk", "dtemp"].join("");

  const trackedTestFiles = (): string[] =>
    execFileSync("git", ["ls-files", "tests"], { encoding: "utf8" })
      .split("\n")
      .filter((file) => file !== "" && /\.tsx?$/.test(file));

  test("only tests/temp-dir.ts (and the allowlisted files) call mkdtemp", () => {
    const offenders = trackedTestFiles()
      .filter((file) => file !== GUARD_FILE && file !== HELPER_FILE && !(file in ALLOWLIST))
      .filter((file) => readFileSync(file, "utf8").includes(NEEDLE));

    expect(
      offenders,
      `${offenders.join(", ")}: use makeTestTempDir from tests/temp-dir.ts instead of calling mkdtemp directly`
    ).toEqual([]);
  });

  test("the allowlist itself still names real, tracked files", () => {
    const tracked = new Set(trackedTestFiles());
    for (const file of Object.keys(ALLOWLIST)) expect(tracked.has(file)).toBe(true);
  });
});
