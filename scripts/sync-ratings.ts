import { writeFileSync } from "node:fs";

import { CLUBS } from "../src/data/clubs";
import { parseTeamRatings } from "./sync-ratings-core";

const SOURCE = "https://ekstraklasa.adrunkhuman.com/";

// The default fetch User-Agent gets a 403 from this host; a browser one does not.
const BROWSER_UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36";

const OUTPUT = new URL("../src/data/team-ratings.ts", import.meta.url);

const main = async (): Promise<void> => {
  const response = await fetch(SOURCE, { headers: { "User-Agent": BROWSER_UA } });
  if (!response.ok) throw new Error(`sync-ratings: ${SOURCE} returned ${response.status}`);
  const clubs = parseTeamRatings(await response.text());

  const clubShortNames = CLUBS.map((club) => club.shortName);
  const known = new Set(clubs.map((club) => club.krotko));
  const missing = clubShortNames.filter((club) => !known.has(club));
  const added = clubs
    .filter((club) => !clubShortNames.includes(club.krotko))
    .map((club) => club.krotko);

  console.log(`Pobrano ${clubs.length} klubow ze zrodla.`);
  if (missing.length > 0) console.log(`Brak w modelu (sa w CLUBS): ${missing.join(", ")}`);
  if (added.length > 0) console.log(`Nowe w modelu (brak w CLUBS): ${added.join(", ")}`);
  if (missing.length > 0 || added.length > 0) {
    console.log("CLUBS zmienia sie osobnym, recznym commitem - patrz spec, rozdzial 3.");
  }

  const rows = clubs
    .map(
      (club) =>
        `  { krotko: ${JSON.stringify(club.krotko)}, nazwa: ${JSON.stringify(club.nazwa)}, attack: ${club.attack}, defence: ${club.defence} },`
    )
    .join("\n");

  writeFileSync(
    OUTPUT,
    `// GENERATED by pnpm sync:ratings - do not edit by hand.\n` +
      `// Source: ${SOURCE} (Dixon-Coles model). Refresh is a deliberate act:\n` +
      `// it invalidates measured constants and requires a golden retrace.\n\n` +
      `import type { TeamRating } from "./types";\n\n` +
      `export const TEAM_RATINGS_SCHEMA_VERSION = 1;\n\n` +
      `export const TEAM_RATINGS = {\n` +
      `  schemaVersion: TEAM_RATINGS_SCHEMA_VERSION,\n` +
      `  snapshotDate: ${JSON.stringify(new Date().toISOString().slice(0, 10))},\n` +
      `  clubs: [\n${rows}\n  ] as readonly TeamRating[],\n} as const;\n`,
    "utf8"
  );
  console.log(`Zapisano ${OUTPUT.pathname}`);
};

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
