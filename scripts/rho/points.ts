/**
 * Recomputes the four rho values task 6 has to simulate and writes them to a
 * pinned module at full precision.
 *
 * Exists so that nobody transcribes them. The report prints four decimals;
 * simulating a rounded rho would answer a question about a different rho than
 * the one measured, and the difference between -0.0644 and the value behind
 * it is the kind of thing that decides a gate whose window is 0.036 wide.
 *
 * Deterministic and cheap - a five-start fit, a profile interval and a
 * separable block bootstrap, about twenty seconds - so the values can be
 * regenerated and checked against `_rho-2026-09-01.md` rather than trusted.
 *
 * Reads nothing but the pinned CSV and writes nothing but the module.
 */
import { writeFileSync } from "node:fs";

import { ALL_SEASONS } from "../match-engine-audit-reference";
import { BLOCK_GRID, separableBlockBootstrap } from "./dixon-coles-blocks";
import { fitProfile, profileInterval } from "./dixon-coles-profile";
import { buildWindow, conservativePercentileInterval, conservativeEnvelope } from "./audit-core";
import { stderrStep } from "./progress";

/** The same constants audit.ts uses, so the two agree by construction. */
const BASE_BLOCK_SEED = 0x1d3c0de + 1_000_000;
const BLOCK_REPLICATIONS = 2000;
const TARGET = "scripts/rho/measured-points.ts";

const main = (): void => {
  const done = stderrStep("dopasowanie, profil i bootstrap blokowy");
  const window = buildWindow(ALL_SEASONS);
  const fit = fitProfile(window.matches, { starts: 5 });
  if (fit.startSpread > 1e-6) {
    throw new Error(`starts disagree by ${fit.startSpread.toExponential(2)}`);
  }
  const profile = profileInterval(window.matches, fit, 0.99);
  const block = separableBlockBootstrap(window, BLOCK_REPLICATIONS, BASE_BLOCK_SEED, BLOCK_GRID);
  const blockInterval = conservativePercentileInterval(block, 0.99);
  if (!blockInterval.estimable) throw new Error("the block interval lost a tail");
  const envelope = conservativeEnvelope(profile, blockInterval);
  done();

  const body = `// GENERATED by pnpm audit:rho-points - do not edit by hand.
//
// The four rho values task 6 of the rho study simulates, at the precision
// they were measured at rather than the four decimals a report prints.
// Regenerate and diff rather than trusting: the command is deterministic.
//
// Source measurement: docs/decisions/_rho-2026-09-01.md
// Method: docs/decisions/rho-estimator-method.md

/** Point estimate on the ten-season window. */
export const RHO_ESTIMATE = ${fit.rho};

/** Lower end of the conservative envelope - here it comes from the block
 * bootstrap, whose interval reaches further than the profile one. */
export const RHO_ENVELOPE_LOWER = ${envelope.lower};

/** Upper end of the conservative envelope - here from the profile interval,
 * four ten-thousandths short of zero. */
export const RHO_ENVELOPE_UPPER = ${envelope.upper};

/** Rendered to four decimals, as strings, so they can be compared with the
 * pinned report character for character - a number literal would lose the
 * trailing zero the report prints. */
export const ROUNDED = {
  estimate: "${fit.rho.toFixed(4)}",
  profile: "[${profile.lower.toFixed(4)}; ${profile.upper.toFixed(4)}]",
  block: "[${blockInterval.lower.toFixed(4)}; ${blockInterval.upper.toFixed(4)}]",
  envelope: "[${envelope.lower.toFixed(4)}; ${envelope.upper.toFixed(4)}]",
} as const;
`;
  writeFileSync(TARGET, body, "utf8");
  process.stderr.write(
    [
      `  ρ̂                 ${fit.rho}`,
      `  profil 99%        [${profile.lower}; ${profile.upper}]`,
      `  blokowy 99%       [${blockInterval.lower}; ${blockInterval.upper}]`,
      `  obwiednia         [${envelope.lower}; ${envelope.upper}]`,
      `  zapisano ${TARGET}`,
      "",
    ].join("\n")
  );
};

main();
